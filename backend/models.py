# ASSISTANT CONVERSATION
# ============================================================

class AssistantConversation(Base):
    """
    Stores lightweight assistant conversation history.

    IMPORTANT:
    Gemini API keys are NEVER stored here.

    The frontend provides the user's API key when invoking
    the assistant. The backend uses it for the request and
    does not persist it.

    Conversation history can be used for:
    - Follow-up questions
    - Job comparison
    - Resume improvement
    - Preparation guidance
    - Personalized job discussions
    """

    __tablename__ = "assistant_conversations"

    # ========================================================
    # PRIMARY IDENTIFICATION
    # ========================================================

    id = Column(
        Integer,
        primary_key=True,
        index=True,
    )

    conversation_id = Column(
        String(255),
        index=True,
        nullable=False,
    )

    profile_id = Column(
        String(255),
        index=True,
        nullable=True,
    )

    # ========================================================
    # MESSAGE
    # ========================================================

    role = Column(
        String(50),
        nullable=False,
    )

    message = Column(
        Text,
        nullable=False,
    )

    # ========================================================
    # OPTIONAL JOB CONTEXT
    # ========================================================

    job_id = Column(
        String(255),
        nullable=True,
        index=True,
    )

    # ========================================================
    # TIMESTAMP
    # ========================================================

    created_at = Column(
        DateTime,
        default=datetime.utcnow,
        nullable=False,
    )

